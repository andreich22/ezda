#!/usr/bin/env node

import fs from "node:fs";
import crypto from "node:crypto";
import { execFileSync } from "node:child_process";

const contextPath = "docs/ai-context.md";
const sources = [
  "AGENTS.md",
  "README.md",
  "package.json",
];

const begin = "<!-- BEGIN:ai-context-fingerprint -->";
const end = "<!-- END:ai-context-fingerprint -->";

function gitBlobSha(path) {
  return execFileSync("git", ["hash-object", path], { encoding: "utf8" }).trim();
}

function readContext() {
  if (!fs.existsSync(contextPath)) {
    throw new Error(`${contextPath} is missing`);
  }
  return fs.readFileSync(contextPath, "utf8");
}

function currentFingerprints() {
  return Object.fromEntries(
    sources.map((path) => {
      if (!fs.existsSync(path)) {
        throw new Error(`Authoritative source is missing: ${path}`);
      }
      return [path, gitBlobSha(path)];
    }),
  );
}

function renderBlock(fingerprints) {
  const lines = [
    begin,
    "<!-- Generated by npm run ai-context:refresh. Do not edit manually. -->",
    ...sources.map((path) => `- \`${path}\`: \`${fingerprints[path]}\``),
    end,
  ];
  return lines.join("\n");
}

function parseRecordedBlock(content) {
  const start = content.indexOf(begin);
  const finish = content.indexOf(end);
  if (start === -1 || finish === -1 || finish < start) {
    return null;
  }

  const block = content.slice(start, finish + end.length);
  const result = {};
  for (const line of block.split("\n")) {
    const match = line.match(/^- \`([^\`]+)\`: \`([0-9a-f]{40})\`$/);
    if (match) result[match[1]] = match[2];
  }
  return result;
}

function replaceBlock(content, block) {
  const start = content.indexOf(begin);
  const finish = content.indexOf(end);
  if (start === -1 || finish === -1 || finish < start) {
    return `${content.trimEnd()}\n\n${block}\n`;
  }
  return `${content.slice(0, start).trimEnd()}\n\n${block}${content.slice(finish + end.length)}`;
}

const mode = process.argv[2] ?? "check";
const context = readContext();
const expected = currentFingerprints();

if (mode === "refresh") {
  const updated = replaceBlock(context, renderBlock(expected));
  fs.writeFileSync(contextPath, updated);
  console.log(`Updated ${contextPath} fingerprint block.`);
  process.exit(0);
}

if (mode !== "check") {
  console.error("Usage: node scripts/validate-ai-context.mjs [check|refresh]");
  process.exit(2);
}

const recorded = parseRecordedBlock(context);
const errors = [];

if (!recorded) {
  errors.push("AI context has no generated fingerprint block. Run npm run ai-context:refresh.");
} else {
  for (const source of sources) {
    if (recorded[source] !== expected[source]) {
      errors.push(
        `${source} changed since the AI context was last refreshed (recorded ${recorded[source] ?? "missing"}, current ${expected[source]}).`,
      );
    }
  }
}

if (!context.includes("AGENTS.md is authoritative")) {
  errors.push("docs/ai-context.md must state that AGENTS.md remains authoritative.");
}

if (errors.length > 0) {
  console.error("AI context freshness check failed:");
  for (const error of errors) console.error(`- ${error}`);
  process.exit(1);
}

console.log("AI context freshness check passed.");
for (const source of sources) {
  console.log(`- ${source}: ${expected[source]}`);
}
